export interface PaperSection {
  title: string;
  body: string[];
}

export interface Publication {
  slug: string;
  title: string;
  authors: string[];
  /** 저자 목록에서 내 이름 — 목록에서 굵게 표시할 때 쓴다. */
  me: string;
  role: string;
  summary: string;
  /** 목록에서 보여줄 짧은 요약 줄. */
  details: string[];
  keywords: string[];
  /** 학회지 이름. 정해지지 않았으면 비워두면 화면에서 빠진다. */
  venue?: string;
  /** 게재 시기. 채우면 제목 옆에 붙는다. */
  period?: string;

  /** 상세 페이지 본문. */
  sections?: PaperSection[];
  /** 상세 페이지 위쪽에 숫자로 보여줄 결과. */
  numbers?: { label: string; value: string }[];
  /**
   * 원문·데이터 링크. 게재되면 DBpia나 RISS 주소를 여기 넣으면 된다.
   * 파일을 올리려면 public/docs/ 에 두고 '/docs/파일명' 으로 적는다.
   */
  documents?: { label: string; href: string; note?: string }[];
}

